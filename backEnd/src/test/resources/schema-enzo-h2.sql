-- Cópia da estrutura do banco do Enzo (pg_dump de 19/10/2026), adaptada para o H2 dos testes:
--   - "point" vira um DOMAIN de texto (o H2 não tem o tipo point);
--   - gen_random_uuid() -> RANDOM_UUID(); text -> VARCHAR.
-- Mantém as mesmas tabelas, colunas, CHECKs e regras ON DELETE.
CREATE DOMAIN IF NOT EXISTS point AS VARCHAR(100);

CREATE TABLE usuarios (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    nome character varying(255) NOT NULL,
    email character varying(255) NOT NULL UNIQUE,
    senha_hash character varying(255) NOT NULL,
    telefone character varying(20),
    nivel_habilidade integer,
    criado_em timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT usuarios_nivel_habilidade_check CHECK (nivel_habilidade >= 1 AND nivel_habilidade <= 5)
);

CREATE TABLE esportes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome character varying(100) NOT NULL,
    quantidade_jogadores_padrao integer
);

CREATE TABLE locais (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    nome character varying(255) NOT NULL,
    endereco character varying(2000) NOT NULL,
    coordenadas point,
    dono_id uuid REFERENCES usuarios(id) ON DELETE SET NULL
);

CREATE TABLE quadras (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    local_id uuid NOT NULL REFERENCES locais(id) ON DELETE CASCADE,
    esporte_id integer NOT NULL REFERENCES esportes(id) ON DELETE RESTRICT,
    nome character varying(255) NOT NULL,
    preco_hora numeric(10,2)
);

CREATE TABLE partidas (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    criador_id uuid NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    quadra_id uuid NOT NULL REFERENCES quadras(id) ON DELETE RESTRICT,
    data_hora_inicio timestamp with time zone NOT NULL,
    data_hora_fim timestamp with time zone NOT NULL,
    max_jogadores integer,
    status character varying(50) DEFAULT 'aberta',
    CONSTRAINT partidas_check CHECK (data_hora_fim > data_hora_inicio)
);

CREATE TABLE partida_participantes (
    partida_id uuid NOT NULL REFERENCES partidas(id) ON DELETE CASCADE,
    usuario_id uuid NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    status_confirmacao character varying(50) DEFAULT 'pendente',
    PRIMARY KEY (partida_id, usuario_id)
);

CREATE TABLE avaliacoes_quadras (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    avaliador_id uuid NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    quadra_id uuid NOT NULL REFERENCES quadras(id) ON DELETE CASCADE,
    nota integer NOT NULL CHECK (nota >= 1 AND nota <= 5),
    comentario character varying(2000),
    criado_em timestamp with time zone DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE avaliacoes_usuarios (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    avaliador_id uuid NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    avaliado_id uuid NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    partida_id uuid REFERENCES partidas(id) ON DELETE SET NULL,
    nota integer NOT NULL CHECK (nota >= 1 AND nota <= 5),
    comentario character varying(2000),
    criado_em timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT avaliacoes_usuarios_check CHECK (avaliador_id <> avaliado_id)
);

CREATE TABLE campeonatos (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    nome character varying(255) NOT NULL,
    esporte_id integer NOT NULL REFERENCES esportes(id),
    organizador_id uuid NOT NULL REFERENCES usuarios(id),
    data_inicio date NOT NULL,
    data_fim date NOT NULL,
    regras character varying(2000),
    CONSTRAINT campeonatos_check CHECK (data_fim >= data_inicio)
);

CREATE TABLE campeonato_equipes (
    id uuid DEFAULT RANDOM_UUID() NOT NULL PRIMARY KEY,
    campeonato_id uuid NOT NULL REFERENCES campeonatos(id) ON DELETE CASCADE,
    nome_equipe character varying(255) NOT NULL,
    capitao_id uuid NOT NULL REFERENCES usuarios(id)
);

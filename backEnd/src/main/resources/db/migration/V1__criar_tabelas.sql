CREATE TABLE esportes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(60)  NOT NULL,
    descricao             VARCHAR(255),
    jogadores_sugeridos   INTEGER,
    ativo                 BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_esportes_nome UNIQUE (nome)
);

CREATE TABLE usuarios (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(100) NOT NULL,
    email                 VARCHAR(150) NOT NULL,
    senha_hash            VARCHAR(100) NOT NULL,
    telefone              VARCHAR(20),
    data_nascimento       DATE,
    cidade                VARCHAR(100),
    bio                   VARCHAR(500),
    nivel                 VARCHAR(20),
    latitude              DOUBLE PRECISION,
    longitude             DOUBLE PRECISION,
    perfil                VARCHAR(20)  NOT NULL DEFAULT 'USER',
    ativo                 BOOLEAN      NOT NULL DEFAULT TRUE,
    consentimento_lgpd_em TIMESTAMP    NOT NULL,
    criado_em             TIMESTAMP    NOT NULL,
    atualizado_em         TIMESTAMP    NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('USER', 'ADMIN')),
    CONSTRAINT ck_usuarios_nivel CHECK (nivel IS NULL OR nivel IN ('INICIANTE', 'INTERMEDIARIO', 'AVANCADO'))
);

-- Esportes favoritos de cada usuário (N:N)
CREATE TABLE usuario_esportes (
    usuario_id            BIGINT NOT NULL,
    esporte_id            BIGINT NOT NULL,
    CONSTRAINT pk_usuario_esportes PRIMARY KEY (usuario_id, esporte_id),
    CONSTRAINT fk_usuario_esportes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_usuario_esportes_esporte FOREIGN KEY (esporte_id) REFERENCES esportes (id) ON DELETE CASCADE
);

CREATE TABLE eventos (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                VARCHAR(100) NOT NULL,
    descricao             VARCHAR(1000),
    esporte_id            BIGINT       NOT NULL,
    organizador_id        BIGINT       NOT NULL,
    data_hora_inicio      TIMESTAMP    NOT NULL,
    duracao_minutos       INTEGER      NOT NULL,
    local_nome            VARCHAR(150) NOT NULL,
    endereco              VARCHAR(255),
    cidade                VARCHAR(100) NOT NULL,
    latitude              DOUBLE PRECISION,
    longitude             DOUBLE PRECISION,
    max_participantes     INTEGER      NOT NULL,
    nivel                 VARCHAR(20)  NOT NULL DEFAULT 'TODOS',
    status                VARCHAR(20)  NOT NULL DEFAULT 'ATIVO',
    criado_em             TIMESTAMP    NOT NULL,
    atualizado_em         TIMESTAMP    NOT NULL,
    CONSTRAINT fk_eventos_esporte FOREIGN KEY (esporte_id) REFERENCES esportes (id),
    CONSTRAINT fk_eventos_organizador FOREIGN KEY (organizador_id) REFERENCES usuarios (id),
    CONSTRAINT ck_eventos_max_participantes CHECK (max_participantes BETWEEN 2 AND 100),
    CONSTRAINT ck_eventos_duracao CHECK (duracao_minutos BETWEEN 15 AND 720),
    CONSTRAINT ck_eventos_nivel CHECK (nivel IN ('TODOS', 'INICIANTE', 'INTERMEDIARIO', 'AVANCADO')),
    CONSTRAINT ck_eventos_status CHECK (status IN ('ATIVO', 'CANCELADO'))
);

CREATE INDEX idx_eventos_data_hora ON eventos (data_hora_inicio);
CREATE INDEX idx_eventos_esporte ON eventos (esporte_id);
CREATE INDEX idx_eventos_organizador ON eventos (organizador_id);
CREATE INDEX idx_eventos_cidade ON eventos (cidade);
CREATE INDEX idx_eventos_localizacao ON eventos (latitude, longitude);

CREATE TABLE participacoes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id             BIGINT      NOT NULL,
    usuario_id            BIGINT      NOT NULL,
    status                VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADO',
    criado_em             TIMESTAMP   NOT NULL,
    atualizado_em         TIMESTAMP   NOT NULL,
    CONSTRAINT uk_participacoes_evento_usuario UNIQUE (evento_id, usuario_id),
    CONSTRAINT fk_participacoes_evento FOREIGN KEY (evento_id) REFERENCES eventos (id) ON DELETE CASCADE,
    CONSTRAINT fk_participacoes_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT ck_participacoes_status CHECK (status IN ('CONFIRMADO', 'CANCELADO'))
);

CREATE INDEX idx_participacoes_usuario ON participacoes (usuario_id);
